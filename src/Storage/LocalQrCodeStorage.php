namespace Islesurlasorguetourisme\SuluQrCodeBundle\Storage;

use Symfony\Component\Filesystem\Filesystem;

/**
 * Stores the files on the local disk, one directory per QR code.
 */
final class LocalQrCodeStorage implements QrCodeStorageInterface
{
    private readonly Filesystem $filesystem;

    public function __construct(
        private readonly string $directory,
        ?Filesystem $filesystem = null,
    ) {
        $this->filesystem = $filesystem ?? new Filesystem();
    }

    public function read(string $qrCodeId, string $fileName): ?string
    {
        $path = $this->path($qrCodeId, $fileName);

        if (!\is_file($path)) {
            return null;
        }

        $content = @\file_get_contents($path);

        return false === $content ? null : $content;
    }

    public function write(string $qrCodeId, string $fileName, string $content): void
    {
        // dumpFile() writes to a temporary file first, then renames it: readers never see a partial image.
        $this->filesystem->dumpFile($this->path($qrCodeId, $fileName), $content);
    }

    public function purge(string $qrCodeId): void
    {
        $this->filesystem->remove($this->directoryOf($qrCodeId));
    }

    private function path(string $qrCodeId, string $fileName): string
    {
        return $this->directoryOf($qrCodeId) . '/' . self::sanitize($fileName);
    }

    private function directoryOf(string $qrCodeId): string
    {
        return \rtrim($this->directory, '/') . '/' . self::sanitize($qrCodeId);
    }

    /**
     * Identifiers and file names are generated by the bundle, but they must never be able to leave the directory.
     */
    private static function sanitize(string $segment): string
    {
        $sanitized = \preg_replace('/[^A-Za-z0-9._-]/', '', $segment) ?? '';

        if ('' === \trim($sanitized, '.')) {
            throw new \InvalidArgumentException(\sprintf('"%s" is not a valid storage path segment.', $segment));
        }

        return $sanitized;
    }
}
